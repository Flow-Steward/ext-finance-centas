#!/usr/bin/env python3
"""Generate every contract of this bundle from tests/reference/op_specs.py.

Output (all generated, never edited by hand):

* ``contracts/operation_manifest.yaml`` — every step
* ``contracts/step_ui_manifest.yaml``   — the builder form of every step
* ``contracts/artifact_policies.yaml``  — the files steps read and save
* ``ui/actions/actions.yaml``           — the same-id workflow-visible actions
* ``ui/pages/centas-api.yaml``, ``ui/pages/coverage.yaml``, ``ui/pages/changelog.yaml``
* ``tests/reference/coverage.json``     — every operation and field of the specification →
  the step input that offers it, or why none does

Run from the bundle root:  python3 tests/reference/build_contracts.py
``tests/test_contracts.py`` fails when the committed files drift from this output.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

import centas_api  # noqa: E402
import op_specs  # noqa: E402

sys.path.insert(0, str(ROOT))
from runtime import files as runtime_files  # noqa: E402
from runtime import transport as runtime_transport  # noqa: E402
from runtime.reference import GITBOOK, SPECIFICATION  # noqa: E402

CONNECTION_TYPE_ID = "centas"
CATEGORY = "finance"
CHANNEL = "centas_ws"
GENERATED_HEADER = (
    "# Generated by tests/reference/build_contracts.py from tests/reference/op_specs.py.\n"
    "# Do not edit by hand: tests/test_contracts.py fails when this file drifts.\n"
)
TEXTAREA_INPUTS = {"note", "customer_note", "comment"}
HIDDEN_RESULTS = {"external_effect_status", "definitely_no_external_effect"}

BASE_ERRORS = [
    "invalid_payload",
    "invalid_host_envelope",
    "invalid_connection",
    "unsupported_operation",
    "internal_error",
]
TRANSPORT_ERRORS = [
    "authentication_failed",
    "not_found",
    "conflict",
    "upstream_validation_failed",
    "upstream_failure",
    "invalid_response",
    "response_too_large",
    "timeout",
    "connection_failed",
    "redirect_rejected",
    "blocked_address",
]

CONNECTION_INPUT = {"name": "connection_ref", "value_type": "connection_ref", "required": True}


def effect_outputs() -> list[dict[str, Any]]:
    return [
        {"name": "external_effect_status", "value_type": "text", "schema": {"type": "string"}},
        {
            "name": "definitely_no_external_effect",
            "value_type": "boolean",
            "schema": {"type": "boolean"},
        },
    ]


def errors_for(spec: dict[str, Any]) -> list[str]:
    codes = [*BASE_ERRORS, *TRANSPORT_ERRORS]
    if spec["kind"] == "action":
        codes.append("timeout_unknown")
    if any(i["value_type"] == "artifact_handle" for i in spec["inputs"]):
        codes.append("artifact_input_unavailable")
    if any(o["value_type"] == "artifact_handle" for o in spec["outputs"]):
        codes.append("artifact_output_unavailable")
    return codes


def _clean_input(item: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in item.items() if k not in {"labels", "wire", "placeholder"}}


def operation(spec: dict[str, Any]) -> dict[str, Any]:
    write = spec["kind"] == "action"
    op: dict[str, Any] = {
        "operation_id": spec["operation_id"],
        "display_name": spec["display_name"],
        "description": spec["description"],
        "operation_kind": spec["kind"],
        "category": CATEGORY,
        "connection_type_ids": [CONNECTION_TYPE_ID],
        "workflow_visible": True,
    }
    if write:
        op["effect_kind"] = f"centas_{spec['operation_id']}"
    outputs = list(spec["outputs"]) + (effect_outputs() if write else [])
    op["inputs"] = [CONNECTION_INPUT, *(_clean_input(i) for i in spec["inputs"])]
    op["outputs"] = outputs
    op["result_fields"] = [f"result.{o['name']}" for o in outputs]
    op["error_codes"] = errors_for(spec)
    return op


ACTION_PARAM_TYPES = {
    "connection_ref": "connection_ref",
    "text": "string",
    "integer": "integer",
    "number": "number",
    "boolean": "boolean",
    "object": "object",
    "array": "array",
    "artifact_handle": "artifact_handle",
}


def action_for(op: dict[str, Any]) -> dict[str, Any]:
    write = op["operation_kind"] == "action"
    action: dict[str, Any] = {
        "action_id": op["operation_id"],
        "title": op["display_name"],
        "description": op["description"],
        "required_scopes": ["extension:invoke"],
        "handler": {"mode": "extension"},
    }
    if write:
        action["command_type"] = "invoke_extension_action"
    action["mutates_platform"] = write
    action["workflow_visible"] = True
    action["parameters"] = [
        {
            "name": i["name"],
            "type": ACTION_PARAM_TYPES[i["value_type"]],
            "required": bool(i.get("required")),
        }
        for i in op["inputs"]
    ]
    action["result_fields"] = [o["name"] for o in op["outputs"]]
    action["error_codes"] = list(op["error_codes"])
    return action


def widget_for(item: dict[str, Any]) -> str:
    schema = item.get("schema") or {}
    if item["value_type"] == "artifact_handle":
        return "artifact_picker"
    if schema.get("enum"):
        return "select"
    if item["name"] in TEXTAREA_INPUTS:
        return "textarea"
    vt = item["value_type"]
    if vt in {"object", "array"}:
        return "json"
    if vt == "boolean":
        return "boolean"
    if vt in {"integer", "number"}:
        return "number"
    return "text"


def form_for(spec: dict[str, Any]) -> dict[str, Any]:
    fields = []
    for item in spec["inputs"]:
        schema = item.get("schema") or {}
        field: dict[str, Any] = {
            "name": item["name"],
            "label": schema.get("title") or item["name"],
            "widget_type": widget_for(item),
            "required": bool(item.get("required")),
        }
        if schema.get("description"):
            field["help_text"] = schema["description"][:400]
        if schema.get("enum"):
            labels = item.get("labels") or {}
            field["options"] = [
                {"label": labels.get(v, str(v)), "value": v} for v in schema["enum"]
            ]
        if item.get("placeholder"):
            field["placeholder"] = item["placeholder"]
        fields.append(field)
    return {"operation_id": spec["operation_id"], "title": spec["display_name"], "fields": fields}


def artifact_policies(specs: list[dict[str, Any]]) -> list[dict[str, Any]]:
    policies: list[dict[str, Any]] = []
    for spec in specs:
        entry: dict[str, Any] = {"operation_id": spec["operation_id"]}
        file_inputs = [i for i in spec["inputs"] if i["value_type"] == "artifact_handle"]
        if file_inputs:
            entry["inputs"] = [
                {
                    "kind": "artifact",
                    "value_type": "artifact_handle",
                    "binding_key": runtime_files.UPLOAD_BINDING,
                    "field": i["name"],
                    "required": bool(i.get("required")),
                    "max_size_bytes": runtime_files.MAX_UPLOAD_BYTES,
                }
                for i in file_inputs
            ]
        if any(o["value_type"] == "artifact_handle" for o in spec["outputs"]):
            take = bool(spec.get("take"))
            entry["outputs"] = [
                {
                    "kind": "artifact",
                    "value_type": "artifact_handle",
                    "binding_key": runtime_files.QUEUE_BINDING
                    if take
                    else runtime_files.PDF_BINDING,
                    "filename": "centas-records.xml" if take else "centas-invoice.pdf",
                    "content_type": runtime_files.QUEUE_CONTENT_TYPE
                    if take
                    else runtime_files.PDF_CONTENT_TYPE,
                    "max_size_bytes": runtime_transport.MAX_TAKE_BYTES
                    if take
                    else runtime_files.MAX_PDF_BYTES,
                    "retention_class": "run_window",
                }
            ]
        if len(entry) > 1:
            policies.append(entry)
    return policies


def external_effects(ops: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [
        {
            "operation_id": op["operation_id"],
            "effect_kind": op["effect_kind"],
            "channel": CHANNEL,
            "idempotency": "required",
            "test_mode_behavior": "suppress",
        }
        for op in ops
        if op["operation_kind"] == "action"
    ]


# -- coverage -----------------------------------------------------------------------


def coverage() -> dict[str, Any]:
    specs = op_specs.steps()
    operations = []
    for name, spec in centas_api.OPERATIONS.items():
        fields = []
        for field, (path, note, source) in spec["fields"].items():
            entry: dict[str, Any] = {"field": field, "input": path, "source": source}
            if note:
                entry["note"] = note
            fields.append(entry)
        row: dict[str, Any] = {"operation": name, "steps": spec["steps"]}
        if spec.get("reason"):
            row["reason"] = spec["reason"]
        row["fields"] = fields
        operations.append(row)
    for spec in specs:
        if not any(spec["operation_id"] in o["steps"] for o in operations):
            raise SystemExit(f"{spec['operation_id']} calls no documented operation")
    return {
        "source": {k: SPECIFICATION[k] for k in ("url", "sha256", "last_modified", "retrieved")},
        "secondary_source": {k: GITBOOK[k] for k in ("url", "sha256", "retrieved")},
        "operations": operations,
        "differences": centas_api.DIFFERENCES,
    }


# -- UI pages -------------------------------------------------------------------------


class _PageDumper(yaml.SafeDumper):
    """Multi-line strings as ``|`` blocks, so the page files read like markdown."""


def _represent_str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    if "\n" in value:
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", value)


_PageDumper.add_representer(str, _represent_str)


def _type_word(schema: dict[str, Any], value_type: str) -> str:
    kinds = schema.get("type")
    kinds = [kinds] if isinstance(kinds, str) else list(kinds or [])
    kinds = [k for k in kinds if k != "null"]
    if schema.get("enum"):
        return "one of " + ", ".join(str(v) for v in schema["enum"])
    if kinds == ["string"] and str(schema.get("pattern") or "").startswith("^\\d{4}"):
        return "date"
    if set(kinds) == {"string", "number"}:
        return "decimal"
    if kinds == ["array"]:
        items = schema.get("items") or {}
        return "list of records" if items.get("properties") else "list"
    if kinds == ["object"]:
        return "record" if schema.get("properties") else "object"
    return {
        "string": "text",
        "integer": "whole number",
        "number": "number",
        "boolean": "yes/no",
    }.get(kinds[0] if len(kinds) == 1 else "", " or ".join(kinds) or value_type)


def _describe(item: dict[str, Any], *, input_side: bool) -> str:
    schema = item.get("schema") or {}
    word = _type_word(schema, item.get("value_type", ""))
    optional = "" if not input_side or item.get("required") else ", optional"
    description = str(schema.get("description") or "").strip()
    record = schema.get("items") if word == "list of records" else schema
    fields = list((record or {}).get("properties") or {})
    if fields and not input_side and word in {"record", "list of records"}:
        shown = ", ".join(f"`{f}`" for f in fields)
        description = f"{description} Fields: {shown}."
    return f"- `{item['name']}` ({word}{optional}){': ' + description if description else ''}"


def api_page(specs: list[dict[str, Any]]) -> dict[str, Any]:
    components = [
        {
            "component_id": "api_overview",
            "type": "markdown",
            "title": "How the steps work",
            "body": (
                "Centas WS (ws.centas.lt) is a two-way exchange between a shop or another "
                "system and the Centas program. The steps send invoices, orders, payments, "
                "products, clients and consignment notes to it, read what the Centas program "
                "uploaded, and — when a workflow plays the Centas program's part — take new "
                "records from its queue.\n\n"
                "- **Sent documents wait in Centas WS** until the Centas program imports "
                "them. A step's success means Centas WS received the document.\n"
                "- **Take steps empty the queue.** Centas WS marks what they hand out, so the "
                "Centas program no longer sees those records as new. Each saves Centas WS's "
                "answer whole as a workflow file.\n"
                "- **Writes are sent once.** Flow Steward remembers every change it made, so "
                "a retried step does not send it twice, and test runs never send. When the "
                "outcome is unclear — a timeout, a lost connection, a refusal, an answer "
                "that cannot be read — the step is not retried: check Centas WS first.\n"
                "- **Totals are checked before sending.** A document whose totals do not "
                "match its lines stops with a conflict and nothing is sent.\n"
                "- **Reads return pages.** Centas WS sends each export whole; the steps "
                "filter it and return up to 500 rows a page.\n"
            ),
        }
    ]
    by_group: dict[str, list[dict[str, Any]]] = {}
    for spec in specs:
        by_group.setdefault(spec["group"], []).append(spec)
    for group in op_specs.GROUPS:
        lines: list[str] = []
        for spec in by_group.get(group, []):
            op = operation(spec)
            kind = (
                "takes records from the Centas WS queue"
                if spec.get("take")
                else "sends data to Centas WS"
                if spec["kind"] == "action"
                else "reads only"
            )
            lines += [
                f"### {spec['display_name']}",
                "",
                spec["description"],
                "",
                f"Action id `{spec['operation_id']}` · {kind} · Centas WS: `{spec['path']}`",
                "",
                "**Inputs**",
                "",
                *(
                    [
                        _describe(i, input_side=True)
                        for i in op["inputs"]
                        if i["name"] != "connection_ref"
                    ]
                    or ["- none"]
                ),
                "",
                "**Results**",
                "",
                *[
                    _describe(o, input_side=False)
                    for o in op["outputs"]
                    if o["name"] not in HIDDEN_RESULTS
                ],
                "",
            ]
        components.append(
            {
                "component_id": "steps_" + group.lower().replace(" ", "_"),
                "type": "markdown",
                "title": group,
                "body": "\n".join(lines).strip() + "\n",
            }
        )
    return {
        "page_id": "centas-api",
        "title": "Centas API",
        "description": "Every Centas step: what it does, which Centas WS call it makes, its "
        "inputs and results.",
        "components": components,
    }


def coverage_page(cov: dict[str, Any]) -> dict[str, Any]:
    names = {s["operation_id"]: s["display_name"] for s in op_specs.steps()}
    lines = [
        "The steps cover the whole Centas WS API as its specification documents it "
        "([Centas WS API documentation](https://ws.centas.lt/api-docs/)): "
        f"{len(cov['operations'])} operations, each documented field either a step input or "
        "listed below with the reason it is not offered.",
        "",
    ]
    for entry in cov["operations"]:
        if entry["steps"]:
            steps = ", ".join(names[s] for s in entry["steps"])
            lines.append(f"- **{entry['operation']}** → {steps}")
        else:
            lines.append(f"- **{entry['operation']}** → {entry['reason']}")
    lines += ["", "### Fields not offered", ""]
    for entry in cov["operations"]:
        if not entry["steps"]:
            continue
        for field in entry["fields"]:
            if field["input"] is None and "token" not in field["field"]:
                lines.append(
                    f"- `{field['field']}` of {entry['operation']}: {field.get('note', '')}"
                )
    lines += [
        "",
        "The key (`token`) is the connection's WS key: in the body of every write and, as "
        "the API requires, in the query of every read.",
    ]
    return {
        "page_id": "coverage",
        "title": "Coverage",
        "description": "What of the documented Centas WS API the steps offer.",
        "components": [
            {
                "component_id": "coverage_summary",
                "type": "markdown",
                "title": "Coverage",
                "body": "\n".join(lines).strip() + "\n",
            }
        ],
    }


def changelog_page() -> dict[str, Any]:
    lines = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8").strip().splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    return {
        "page_id": "changelog",
        "title": "Changelog",
        "description": "What changed in each release of this extension.",
        "components": [
            {
                "component_id": "changelog_entries",
                "type": "markdown",
                "title": "Release history",
                "body": "\n".join(line.rstrip() for line in lines).strip() + "\n",
            }
        ],
    }


# -- output ---------------------------------------------------------------------------


def outputs() -> dict[str, Any]:
    """Every generated file: path -> content (YAML/JSON payloads or pages)."""
    specs = op_specs.steps()
    ops = [operation(s) for s in specs]
    return {
        "contracts/operation_manifest.yaml": {"operations": ops},
        "contracts/step_ui_manifest.yaml": {"forms": [form_for(s) for s in specs]},
        "contracts/artifact_policies.yaml": {"artifact_policies": artifact_policies(specs)},
        "ui/actions/actions.yaml": {"actions": [action_for(op) for op in ops]},
        "ui/pages/centas-api.yaml": api_page(specs),
        "ui/pages/coverage.yaml": coverage_page(coverage()),
        "ui/pages/changelog.yaml": changelog_page(),
        "tests/reference/coverage.json": coverage(),
        "external_effects": external_effects(ops),
    }


def render(path: str, payload: Any) -> str:
    if path.endswith(".json"):
        return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    if path.startswith("ui/pages/"):
        text = yaml.dump(
            payload, Dumper=_PageDumper, sort_keys=False, allow_unicode=True, width=1000
        )
        return GENERATED_HEADER + text
    return GENERATED_HEADER + yaml.safe_dump(
        payload, sort_keys=False, allow_unicode=True, width=100
    )


def main() -> None:
    for path, payload in outputs().items():
        if path == "external_effects":
            continue
        (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / path).write_text(render(path, payload), encoding="utf-8")


if __name__ == "__main__":
    main()
